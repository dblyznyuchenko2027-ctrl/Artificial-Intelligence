"""Адаптери до функцій, які оцінюються.

Набір прикладів, перевірки й звіт не знають, що саме оцінюють: чернетку
відповіді з ПР11 чи помічника з інструментами з ПР8. Усе, що залежить
від конкретної функції, зібрано в адаптері — одному модулі на функцію:

* `setup()` — підключити застосунок (він імпортується зі своєї папки як
  є, нічого не копіюється) і повернути чинну конфігурацію: провайдер,
  модель, версію prompt, температуру — те, що йде в метадані прогону,
  щоб «до» і «після» було з чим порівнювати;
* `before_case(case)` — підготувати стан перед прикладом (скинути дані
  магазину, зареєструвати приклад для підставного провайдера);
* `run(case) -> dict` — виконати один приклад і повернути результат у
  спільному вигляді (нижче).

Результат адаптера — словник зі спільними полями; перевірки працюють
лише з ними:

    text           відповідь функції; None, якщо її немає
    status         "ok" — функція відповіла; "error" — контрольовано
                   відмовила (виняток з видом, порожній вхід тощо)
    error          {"kind": ..., "message": ...} при status == "error"
    calls          журнал викликів інструментів: [{"name", "arguments",
                   "status", ...}]; для чернетки — порожній список
    system_prompt  текст системної інструкції, якщо адаптер його знає
                   (для перевірки витоку інструкції)
    model, provider, usage, cost, elapsed, warnings, rounds, stopped

Новий адаптер (наприклад, до workflow з ПР9) — новий модуль поруч і
рядок у `TARGETS`.
"""

import importlib

TARGETS = {
    "drafts": "targets.drafts",   # помічник оператора з ПР11: чернетка відповіді
    "agent": "targets.agent",     # помічник клієнта з ПР8: інструменти
}


def load(name: str):
    """Імпортувати адаптер за назвою функції."""
    if name not in TARGETS:
        raise SystemExit(f"невідома функція: {name}; є такі: {', '.join(TARGETS)}")
    return importlib.import_module(TARGETS[name])
