"""Обмеження частоти звертань до власного API.

Ліміт провайдера — спільний на весь застосунок: якщо один користувач
сторінки натисне «скласти чернетку» двадцять разів за хвилину, 429 від
провайдера отримають усі. Тому веб-рівень обмежує кожного клієнта ще до
того, як запит дійде до шлюзу. Це інше обмеження, ніж `MAX_CONCURRENT`
у шлюзі: там — скільки звертань до провайдера виконується одночасно на
всіх, тут — скільки запитів за вікно часу дозволено одному.

Хто такий «клієнт», вирішує веб-рівень: сторінка надсилає свій
ідентифікатор у полі `client`. У справжньому застосунку це був би
користувач із сесії або ключ API.

Рішення:

* **Алгоритм — ковзне вікно (журнал часу звертань)**: клієнт може
  зробити не більше `PER_MINUTE` звертань за будь-які 60 секунд.
  Кошик жетонів дозволяє сплески й дає «чесний» Retry-After лише
  приблизно; вікно дає точний: `retry_after` = момент, коли
  найстаріше звертання вікна вийде за його межі (`oldest + 60 − now`).
  Через стільки секунд запит гарантовано пройде (якщо ніхто інший
  від цього клієнта не встигне вперед).
* **Вичерпано** → відмова одразу (`RateLimited`), а не черга: оператор
  чекає на чернетку й має знати причину; мовчазне очікування — те, чого
  не можна робити. Веб-рівень перетворює виняток на 429 із
  `Retry-After`. (Черга до *провайдера* — окремо, у шлюзі, і видима.)
* **Що рахується**: кожне прийняте замовлення, навіть якщо генерація
  потім провалилась — токени (чи принаймні спроби) були витрачені, а
  «повертати дозвіл» дозволило б обійти ліміт збоєм. Відхилені
  замовлення (невідоме звернення тощо) не рахуються — веб-рівень
  перевіряє їх до `acquire`. Відмови з 429 також не продовжують вікно.
* **Памʼять**: журнал клієнта містить не більше `PER_MINUTE` міток;
  неактивні клієнти прибираються.
"""

import collections
import os
import threading
import time

from dotenv import load_dotenv

load_dotenv()

PER_MINUTE = int(os.getenv("RATE_LIMIT_PER_MINUTE", "10"))
WINDOW = 60.0

_hits: dict[str, collections.deque] = {}
_lock = threading.Lock()
_clock = time.monotonic  # підміняється в тестах


class RateLimited(Exception):
    """Ліміт вичерпано. `retry_after` — через скільки секунд пробувати."""

    def __init__(self, retry_after: float) -> None:
        super().__init__(f"ліміт вичерпано, повторіть через {retry_after:.0f} с")
        self.retry_after = retry_after


def settings() -> dict:
    """Чинні обмеження — для сторінки."""
    return {"per_minute": PER_MINUTE}


def _prune(now: float) -> None:
    for key in [k for k, q in _hits.items() if not q or now - q[-1] >= WINDOW]:
        del _hits[key]


def acquire(client: str) -> None:
    """Зарахувати одне звертання клієнта або підняти `RateLimited`.

    Викликається веб-рівнем перед створенням кожної чернетки.
    """
    now = _clock()
    with _lock:
        if len(_hits) > 1000:
            _prune(now)
        q = _hits.setdefault(client, collections.deque())
        while q and now - q[0] >= WINDOW:
            q.popleft()
        if len(q) >= PER_MINUTE:
            raise RateLimited(max(0.1, q[0] + WINDOW - now))
        q.append(now)
